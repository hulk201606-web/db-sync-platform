package com.dbsync.dialect.postgresql;

import static org.assertj.core.api.Assertions.assertThat;

import com.dbsync.common.model.ColumnMeta;
import com.dbsync.common.model.TableMeta;
import com.dbsync.common.options.MappingOptions;
import com.dbsync.common.options.TriggerOptions;
import com.dbsync.common.options.TypeMappingOptions;
import com.dbsync.dialect.DialectFixtures;
import java.util.List;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * PostgreSQL 方言纯字符串断言。
 */
class PostgresDialectTest {

    private final PostgresDialect dialect = new PostgresDialect();

    @Test
    @DisplayName("upsert 用 ON CONFLICT + EXCLUDED")
    void should_useOnConflict_When_buildUpsertSql() {
        String sql = dialect.buildUpsertSql(DialectFixtures.compositePk(),
                List.of("TENANT_ID", "ORDER_ID"), List.of("TENANT_ID", "ORDER_ID", "QTY"));
        assertThat(sql).contains("ON CONFLICT (\"TENANT_ID\", \"ORDER_ID\")");
        assertThat(sql).contains("DO UPDATE SET \"QTY\" = EXCLUDED.\"QTY\"");
        assertThat(sql).doesNotContain("EXCLUDED.\"ORDER_ID\"");
    }

    @Test
    @DisplayName("建表 DDL 不含 COMMENT（注释走 COMMENT ON）")
    void should_notInlineComment_When_createTableDdl() {
        String ddl = dialect.createTableDdl(DialectFixtures.singlePk(), MappingOptions.defaults());
        assertThat(ddl).contains("CREATE TABLE");
        assertThat(ddl).contains("\"ID\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY");
        assertThat(ddl).contains("PRIMARY KEY (\"ID\")");
        assertThat(ddl).contains("UNIQUE (\"NAME\")");
        assertThat(ddl).doesNotContain("COMMENT");
    }

    @Test
    @DisplayName("commentDdl 返回非空且含 COMMENT ON TABLE")
    void should_emitCommentOn_When_commentDdl() {
        List<String> ddl = dialect.commentDdl(DialectFixtures.singlePk(), MappingOptions.defaults());
        assertThat(ddl).isNotEmpty();
        assertThat(ddl.get(0)).contains("COMMENT ON TABLE").contains("订单表");
        assertThat(ddl).anyMatch(s -> s.contains("COMMENT ON COLUMN"));
    }

    @Test
    @DisplayName("索引单独 CREATE INDEX（唯一键已在表内）")
    void should_createIndexSeparately_When_nonUnique() {
        List<String> ddl = dialect.createIndexDdl(DialectFixtures.singlePk(),
                MappingOptions.defaults());
        assertThat(ddl).hasSize(1);
        assertThat(ddl.get(0)).contains("CREATE INDEX \"IDX_ORDER_AMT\" ON");
    }

    @Test
    @DisplayName("分页用 LIMIT n OFFSET m")
    void should_useLimitOffset_When_buildPageSql() {
        assertThat(dialect.buildPageSql("SELECT 1", 20, 10)).isEqualTo("SELECT 1 LIMIT 10 OFFSET 20");
        assertThat(dialect.buildRangePredicate("\"id\"", true)).isEqualTo("\"id\" <= ?");
        assertThat(dialect.buildRangePredicate("\"id\"", false)).isEqualTo("\"id\" < ?");
        assertThat(dialect.quote("a\"b")).isEqualTo("\"a\"\"b\"");
    }

    @Test
    @DisplayName("类型映射与能力声明")
    void should_mapTypesAndCapabilities_When_postgres() {
        TypeMappingOptions opts = TypeMappingOptions.defaults();
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "NUMBER").size(9).build(), opts))
                .isEqualTo("INTEGER");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "NUMBER").size(19).build(), opts))
                .isEqualTo("BIGINT");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "CLOB").build(), opts))
                .isEqualTo("TEXT");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "BLOB").build(), opts))
                .isEqualTo("BYTEA");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "NUMBER").build(), opts))
                .isEqualTo("NUMERIC(38,10)");
        assertThat(dialect.capabilities().supportsOnConflict()).isTrue();
        assertThat(dialect.capabilities().maxIdentifierLength()).isEqualTo(63);
        assertThat(dialect.capabilities().supportsIdentityInsert()).isTrue();
        assertThat(dialect.capabilities().supportsCommentOn()).isTrue();
    }

    @Test
    @DisplayName("触发器为函数 + 触发器两条，含 plpgsql / EXECUTE FUNCTION / RETURN OLD")
    void should_generateTwoStatements_When_createTriggerDdl() {
        TableMeta t = DialectFixtures.singlePk();
        List<String> trigger = dialect.trigger().createTriggerDdl(t, TriggerOptions.defaults());
        assertThat(trigger).hasSize(2);
        assertThat(trigger.get(0)).contains("LANGUAGE plpgsql").contains("RETURN OLD")
                .contains("TG_OP");
        assertThat(trigger.get(1)).contains("EXECUTE FUNCTION")
                .contains("AFTER INSERT OR UPDATE OR DELETE");
        assertThat(dialect.trigger().pollSql("\"T_ORDER_SYNC_LOG\"", 5L, 100))
                .contains("WHERE \"id\" > 5");
    }
}
