package com.dbsync.dialect.db2;

import static org.assertj.core.api.Assertions.assertThat;

import com.dbsync.common.model.ColumnMeta;
import com.dbsync.common.model.TableMeta;
import com.dbsync.common.options.MappingOptions;
import com.dbsync.common.options.TriggerOptions;
import com.dbsync.common.options.TypeMappingOptions;
import com.dbsync.dialect.DialectFixtures;
import java.util.List;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * DB2 方言纯字符串断言（语法最特殊，逐条对照架构 §5.2/§5.3）。
 */
class Db2DialectTest {

    private final Db2Dialect dialect = new Db2Dialect();

    @Test
    @DisplayName("upsert 用 MERGE + SYSIBM.SYSDUMMY1 + CAST")
    void should_useMergeWithCast_When_buildUpsertSql() {
        String sql = dialect.buildUpsertSql(DialectFixtures.compositePk(),
                List.of("TENANT_ID", "ORDER_ID"), List.of("TENANT_ID", "ORDER_ID", "QTY"));
        assertThat(sql).contains("MERGE INTO \"T_ORDER_ITEM\" AS tgt");
        assertThat(sql).contains("FROM SYSIBM.SYSDUMMY1");
        assertThat(sql).contains("CAST(? AS BIGINT) AS \"TENANT_ID\"");
        assertThat(sql).contains("AS src ON");
        assertThat(sql).contains("WHEN MATCHED THEN UPDATE SET");
        assertThat(sql).contains("WHEN NOT MATCHED THEN INSERT");
    }

    @Test
    @DisplayName("分页用 OFFSET n ROWS FETCH NEXT m ROWS ONLY")
    void should_useOffsetFetch_When_buildPageSql() {
        assertThat(dialect.buildPageSql("SELECT * FROM t", 100, 50))
                .isEqualTo("SELECT * FROM t OFFSET 100 ROWS FETCH NEXT 50 ROWS ONLY");
        assertThat(dialect.buildRangePredicate("\"ID\"", true)).isEqualTo("\"ID\" <= ?");
    }

    @Test
    @DisplayName("触发器含 REFERENCING NEW AS N / MODE DB2SQL / N. 前缀")
    void should_referenceNewAsN_When_createTriggerDdl() {
        TableMeta t = DialectFixtures.singlePk();
        List<String> triggers = dialect.trigger().createTriggerDdl(t, TriggerOptions.defaults());
        assertThat(triggers).hasSize(3);
        assertThat(triggers.get(0)).contains("REFERENCING NEW AS N").contains("MODE DB2SQL")
                .contains("N.\"ID\"");
        assertThat(triggers.get(1)).contains("REFERENCING NEW AS N OLD AS O");
        assertThat(triggers.get(2)).contains("REFERENCING OLD AS O").contains("O.\"ID\"");
        assertThat(dialect.trigger().pollSql("\"T_ORDER_SYNC_LOG\"", 7L, 200))
                .contains("FETCH FIRST 200 ROWS ONLY");
    }

    @Test
    @DisplayName("类型映射：NUMBER→DECIMAL、CLOB→CLOB(1M)、DATE→TIMESTAMP(3)")
    void should_mapTypes_When_db2() {
        TypeMappingOptions opts = TypeMappingOptions.defaults();
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "NUMBER").size(10)
                .decimalDigits(2).build(), opts)).isEqualTo("DECIMAL(10,2)");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "NUMBER").build(), opts))
                .isEqualTo("DECIMAL(38,10)");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "VARCHAR2").size(64).build(), opts))
                .isEqualTo("VARCHAR(64)");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "CLOB").build(), opts))
                .isEqualTo("CLOB(1M)");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "BLOB").build(), opts))
                .isEqualTo("BLOB(1M)");
        assertThat(dialect.mapType(ColumnMeta.builder("A", 1, "DATE").build(), opts))
                .isEqualTo("TIMESTAMP(3)");
    }

    @Test
    @DisplayName("能力：128 字符标识符、批 500、支持多值插入")
    void should_declareCapabilities_When_db2() {
        assertThat(dialect.capabilities().maxIdentifierLength()).isEqualTo(128);
        assertThat(dialect.capabilities().recommendedBatchSize()).isEqualTo(500);
        assertThat(dialect.capabilities().supportsMultiRowValues()).isTrue();
        assertThat(dialect.capabilities().supportsIdentityInsert()).isTrue();
        assertThat(dialect.capabilities().supportsMerge()).isTrue();
        assertThat(dialect.capabilities().needsFetchSizeCursor()).isFalse();
        assertThat(dialect.driverClassName()).isEqualTo("com.ibm.db2.jcc.DB2Driver");
    }

    @Test
    @DisplayName("建表 DDL 含双引号标识符、自增子句与主键")
    void should_generateDdl_When_db2CreateTable() {
        String ddl = dialect.createTableDdl(DialectFixtures.singlePk(), MappingOptions.defaults());
        assertThat(ddl).contains("CREATE TABLE \"APP\".\"T_ORDER\"");
        assertThat(ddl).contains("\"ID\" DECIMAL(19) NOT NULL GENERATED BY DEFAULT AS IDENTITY");
        assertThat(ddl).contains("PRIMARY KEY (\"ID\")");
        assertThat(ddl).contains("UNIQUE (\"NAME\")");
        assertThat(ddl).doesNotContain("COMMENT '主键'");
        assertThat(dialect.commentDdl(DialectFixtures.singlePk(), MappingOptions.defaults()))
                .isNotEmpty();
    }
}
