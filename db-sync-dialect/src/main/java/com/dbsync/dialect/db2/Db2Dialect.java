package com.dbsync.dialect.db2;

import com.dbsync.common.enums.DbType;
import com.dbsync.common.model.ColumnMeta;
import com.dbsync.common.model.TableMeta;
import com.dbsync.common.options.MappingOptions;
import com.dbsync.common.options.TypeMappingOptions;
import com.dbsync.dialect.AbstractDialect;
import com.dbsync.dialect.Capabilities;
import com.dbsync.dialect.Dialect;
import com.dbsync.dialect.MetadataReader;
import com.dbsync.dialect.TriggerDdlGenerator;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * IBM DB2 LUW 11.5 方言（语法最特殊的一个）。
 *
 * <p>关键差异：
 * <ul>
 *   <li>{@code MERGE} 的 {@code USING} 子查询<b>必须 CAST</b>，否则 DB2 推断类型失败；</li>
 *   <li>无 FROM 的子查询要写 {@code FROM SYSIBM.SYSDUMMY1}；</li>
 *   <li>分页用 {@code OFFSET ? ROWS FETCH NEXT ? ROWS ONLY}；</li>
 *   <li>触发器必须 {@code REFERENCING NEW AS N} + {@code MODE DB2SQL}。</li>
 * </ul>
 */
public final class Db2Dialect extends AbstractDialect implements Dialect {

    private static final Capabilities CAPS = new Capabilities(
            false,   // supportsSkipLocked
            true,    // supportsMerge
            false,   // supportsOnConflict
            false,   // supportsOnDuplicateKey
            true,    // supportsIdentityInsert
            true,    // supportsIdentityRestart
            false,   // needsFetchSizeCursor
            true,    // supportsCommentOn
            true,    // supportsMultiRowValues
            true,    // supportsBatchGeneratedKeys
            true,    // supportsStreamingBlob
            false,   // caseSensitiveIdentifiers
            128,     // maxIdentifierLength
            500,     // recommendedBatchSize
            "CURRENT SCHEMA");

    private final MetadataReader metadataReader = new Db2MetadataReader();
    private final TriggerDdlGenerator triggerGenerator = new Db2TriggerDdlGenerator();

    @Override
    public DbType type() {
        return DbType.DB2;
    }

    @Override
    public String driverClassName() {
        return DbType.DB2.driverClassName();
    }

    @Override
    protected char quoteChar() {
        return '"';
    }

    @Override
    protected boolean supportsIfNotExists() {
        return false;
    }

    @Override
    protected String buildIdentityClause(ColumnMeta col) {
        return col.isAutoIncrement() ? " GENERATED BY DEFAULT AS IDENTITY" : "";
    }

    @Override
    public String mapType(ColumnMeta src, TypeMappingOptions opts) {
        TypeMappingOptions options = opts == null ? TypeMappingOptions.defaults() : opts;
        String t = src.getTypeName() == null ? "VARCHAR" : src.getTypeName().toUpperCase(Locale.ROOT);
        int size = src.getSize();
        int scale = src.getDecimalDigits();
        switch (t) {
            case "NUMBER":
            case "DECIMAL":
            case "NUMERIC":
                if (size <= 0) {
                    return "DECIMAL(" + options.getDefaultNumberPrecision() + ","
                            + options.getDefaultNumberScale() + ")";
                }
                if (scale <= 0) {
                    return "DECIMAL(" + size + ")";
                }
                return "DECIMAL(" + size + "," + scale + ")";
            case "INT":
            case "INTEGER":
                return "INTEGER";
            case "BIGINT":
                return "BIGINT";
            case "SMALLINT":
                return "SMALLINT";
            case "TINYINT":
                return "SMALLINT";
            case "VARCHAR":
            case "VARCHAR2":
            case "NVARCHAR2":
            case "NVARCHAR":
                return "VARCHAR(" + (size > 0 ? size : 255) + ")";
            case "CHAR":
            case "NCHAR":
                return "CHAR(" + (size > 0 ? size : 1) + ")";
            case "CLOB":
            case "NCLOB":
            case "TEXT":
            case "LONGTEXT":
                return "CLOB(1M)";
            case "BLOB":
            case "LONGBLOB":
            case "BYTEA":
                return "BLOB(1M)";
            case "DATE":
            case "DATETIME":
            case "TIMESTAMP":
            case "TIMESTAMP WITH TIME ZONE":
                return "TIMESTAMP(3)";
            case "FLOAT":
            case "BINARY_FLOAT":
            case "REAL":
                return "REAL";
            case "DOUBLE":
            case "BINARY_DOUBLE":
            case "DOUBLE PRECISION":
                return "DOUBLE";
            case "BOOLEAN":
            case "BIT":
                return "SMALLINT";
            default:
                return size > 0 ? t + "(" + size + ")" : t;
        }
    }

    @Override
    protected String buildColumnDef(ColumnMeta col, MappingOptions opts,
                                    Map<String, String> columnOverrides) {
        return quoteTarget(col.getName(), opts) + " "
                + effectiveType(col, opts, columnOverrides)
                + nullabilityAndDefault(col) + buildIdentityClause(col);
    }

    @Override
    public String buildUpsertSql(TableMeta table, List<String> pkCols, List<String> cols) {
        String selectList = cols.stream()
                .map(c -> "CAST(? AS " + castTypeOf(table, c) + ") AS " + quote(c))
                .collect(Collectors.joining(", "));
        String on = pkCols.stream().map(c -> "tgt." + quote(c) + " = src." + quote(c))
                .collect(Collectors.joining(" AND "));
        List<String> updates = cols.stream().filter(c -> !containsIgnoreCase(pkCols, c))
                .map(c -> "tgt." + quote(c) + " = src." + quote(c))
                .collect(Collectors.toList());
        StringBuilder sb = new StringBuilder("MERGE INTO ").append(quote(table.getTableName()))
                .append(" AS tgt USING (SELECT ").append(selectList)
                .append(" FROM SYSIBM.SYSDUMMY1) AS src ON ").append(on);
        if (!updates.isEmpty()) {
            sb.append(" WHEN MATCHED THEN UPDATE SET ").append(String.join(", ", updates));
        }
        sb.append(" WHEN NOT MATCHED THEN INSERT (").append(joinColumns(cols))
                .append(") VALUES (")
                .append(cols.stream().map(c -> "src." + quote(c)).collect(Collectors.joining(", ")))
                .append(")");
        return sb.toString();
    }

    @Override
    public String buildPageSql(String baseSql, long offset, int limit) {
        return (baseSql == null ? "" : baseSql) + " OFFSET " + offset + " ROWS FETCH NEXT "
                + limit + " ROWS ONLY";
    }

    @Override
    public MetadataReader metadata() {
        return metadataReader;
    }

    @Override
    public TriggerDdlGenerator trigger() {
        return triggerGenerator;
    }

    @Override
    public Capabilities capabilities() {
        return CAPS;
    }

    /**
     * 计算 CAST 目标类型（DB2 必须先 CAST 才能推断参数类型）。
     *
     * @param table 表元数据
     * @param col   列名
     * @return 类型串
     */
    private String castTypeOf(TableMeta table, String col) {
        return table.column(col)
                .map(c -> mapType(c, TypeMappingOptions.defaults()))
                .orElse("VARCHAR(255)");
    }

    private boolean containsIgnoreCase(List<String> cols, String col) {
        for (String c : cols) {
            if (c.equalsIgnoreCase(col)) {
                return true;
            }
        }
        return false;
    }
}
