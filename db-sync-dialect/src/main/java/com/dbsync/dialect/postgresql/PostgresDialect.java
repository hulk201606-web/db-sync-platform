package com.dbsync.dialect.postgresql;

import com.dbsync.common.enums.DbType;
import com.dbsync.common.model.ColumnMeta;
import com.dbsync.common.model.IndexMeta;
import com.dbsync.common.model.TableMeta;
import com.dbsync.common.options.MappingOptions;
import com.dbsync.common.options.TypeMappingOptions;
import com.dbsync.dialect.AbstractDialect;
import com.dbsync.dialect.Capabilities;
import com.dbsync.dialect.Dialect;
import com.dbsync.dialect.MetadataReader;
import com.dbsync.dialect.TriggerDdlGenerator;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * PostgreSQL 12+ 方言。
 *
 * <p>关键特征：双引号、{@code ON CONFLICT ... DO UPDATE SET c = EXCLUDED.c}、
 * 注释必须走 {@code COMMENT ON}（不在 CREATE TABLE 内）、标识列用
 * {@code GENERATED BY DEFAULT AS IDENTITY}。
 *
 * <p>注意：{@code EXECUTE FUNCTION} 是 PG 11+；若客户是 PG 10 需改 {@code EXECUTE PROCEDURE}。
 */
public final class PostgresDialect extends AbstractDialect implements Dialect {

    private static final Capabilities CAPS = new Capabilities(
            true,    // supportsSkipLocked
            false,   // supportsMerge
            true,    // supportsOnConflict
            false,   // supportsOnDuplicateKey
            true,    // supportsIdentityInsert（OVERRIDING SYSTEM VALUE）
            true,    // supportsIdentityRestart
            false,   // needsFetchSizeCursor（但 autocommit=false + fetchSize 才走游标）
            true,    // supportsCommentOn
            true,    // supportsMultiRowValues
            true,    // supportsBatchGeneratedKeys
            true,    // supportsStreamingBlob
            false,   // caseSensitiveIdentifiers
            63,      // maxIdentifierLength
            1000,    // recommendedBatchSize
            "current_schema()");

    private final MetadataReader metadataReader = new PostgresMetadataReader();
    private final TriggerDdlGenerator triggerGenerator = new PostgresTriggerDdlGenerator();

    @Override
    public DbType type() {
        return DbType.POSTGRESQL;
    }

    @Override
    public String driverClassName() {
        return DbType.POSTGRESQL.driverClassName();
    }

    @Override
    protected char quoteChar() {
        return '"';
    }

    @Override
    protected String uniqueClause(IndexMeta idx, MappingOptions opts) {
        return "UNIQUE (" + joinTargetColumns(idx.getColumns(), opts) + ")";
    }

    @Override
    protected String buildIdentityClause(ColumnMeta col) {
        return col.isAutoIncrement() ? " GENERATED BY DEFAULT AS IDENTITY" : "";
    }

    @Override
    public String mapType(ColumnMeta src, TypeMappingOptions opts) {
        TypeMappingOptions options = opts == null ? TypeMappingOptions.defaults() : opts;
        String t = src.getTypeName() == null ? "VARCHAR" : src.getTypeName().toUpperCase(Locale.ROOT);
        int size = src.getSize();
        int scale = src.getDecimalDigits();
        switch (t) {
            case "NUMBER":
            case "DECIMAL":
            case "NUMERIC":
                if (size <= 0) {
                    // R9：Oracle 无精度 NUMBER 默认 NUMERIC(38,10)
                    return "NUMERIC(" + options.getDefaultNumberPrecision() + ","
                            + options.getDefaultNumberScale() + ")";
                }
                if (scale <= 0 && size <= 9) {
                    return "INTEGER";
                }
                if (scale <= 0 && size <= 19) {
                    return "BIGINT";
                }
                return "NUMERIC(" + size + "," + Math.max(0, scale) + ")";
            case "INT":
            case "INTEGER":
                return "INTEGER";
            case "BIGINT":
                return "BIGINT";
            case "SMALLINT":
                return "SMALLINT";
            case "TINYINT":
                return "SMALLINT";
            case "VARCHAR":
            case "VARCHAR2":
            case "NVARCHAR2":
            case "NVARCHAR":
                return "VARCHAR(" + (size > 0 ? size : 255) + ")";
            case "CHAR":
            case "NCHAR":
                return "CHAR(" + (size > 0 ? size : 1) + ")";
            case "CLOB":
            case "NCLOB":
            case "TEXT":
            case "LONGTEXT":
                return "TEXT";
            case "BLOB":
            case "LONGBLOB":
            case "BINARY":
            case "VARBINARY":
                return "BYTEA";
            case "DATE":
            case "DATETIME":
            case "TIMESTAMP":
            case "TIMESTAMP WITH TIME ZONE":
            case "TIMESTAMP WITH LOCAL TIME ZONE":
                return "TIMESTAMP(3)";
            case "FLOAT":
            case "BINARY_FLOAT":
            case "REAL":
                return "REAL";
            case "DOUBLE":
            case "BINARY_DOUBLE":
            case "DOUBLE PRECISION":
                return "DOUBLE PRECISION";
            case "BOOLEAN":
            case "BIT":
                return "BOOLEAN";
            default:
                return size > 0 ? t + "(" + size + ")" : t;
        }
    }

    @Override
    protected String buildColumnDef(ColumnMeta col, MappingOptions opts,
                                    Map<String, String> columnOverrides) {
        StringBuilder sb = new StringBuilder();
        sb.append(quoteTarget(col.getName(), opts)).append(' ')
                .append(effectiveType(col, opts, columnOverrides));
        sb.append(nullabilityAndDefault(col));
        sb.append(buildIdentityClause(col));
        // 注释不在这里（PG 必须用 COMMENT ON）
        return sb.toString();
    }

    @Override
    public String buildUpsertSql(TableMeta table, List<String> pkCols, List<String> cols) {
        StringBuilder sb = new StringBuilder("INSERT INTO ").append(quote(table.getTableName()))
                .append(" (").append(joinColumns(cols)).append(") VALUES (")
                .append(cols.stream().map(c -> "?").collect(java.util.stream.Collectors.joining(", ")))
                .append(") ON CONFLICT (")
                .append(joinColumns(pkCols))
                .append(")");
        List<String> updates = new java.util.ArrayList<>();
        for (String c : cols) {
            if (!containsIgnoreCase(pkCols, c)) {
                updates.add(quote(c) + " = EXCLUDED." + quote(c));
            }
        }
        if (updates.isEmpty()) {
            sb.append(" DO NOTHING");
        } else {
            sb.append(" DO UPDATE SET ").append(String.join(", ", updates));
        }
        return sb.toString();
    }

    @Override
    public String buildPageSql(String baseSql, long offset, int limit) {
        return (baseSql == null ? "" : baseSql) + " LIMIT " + limit + " OFFSET " + offset;
    }

    @Override
    public MetadataReader metadata() {
        return metadataReader;
    }

    @Override
    public TriggerDdlGenerator trigger() {
        return triggerGenerator;
    }

    @Override
    public Capabilities capabilities() {
        return CAPS;
    }

    /**
     * 判断列名是否在主键集合中（忽略大小写）。
     *
     * @param cols 主键列
     * @param col  目标列
     * @return true 表示是主键列
     */
    private boolean containsIgnoreCase(List<String> cols, String col) {
        for (String c : cols) {
            if (c.equalsIgnoreCase(col)) {
                return true;
            }
        }
        return false;
    }
}
